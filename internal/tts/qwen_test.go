func TestQwen(t *testing.T) {
	ctx := context.Background()
	cfg := config.Load()

	ttsProvider := NewQwenClient(cfg.DashScopeAPIKey, "", cfg.AudioDir)
	msg := `小朋友们，今天咱们来讲《三国演义》第二回的故事。

先来说说张飞怒鞭督邮的事儿。有一天，张飞喝了几杯闷酒，骑着马从馆驿前面经过。他看见五六十个老人在门前哭得特别伤心。张飞就问他们为啥哭，老人们说：“督邮逼着县吏，想要害刘公。我们来苦苦哀求，不但不让进去，还被把门的人赶打。”张飞一听，可生气啦！他瞪圆了眼睛，咬碎了钢牙，一下子从马上跳下来，直接冲进了馆驿。把门的人哪能拦得住他呀！张飞一直跑到后堂，看见督邮正坐在厅上，还把县吏绑在地上呢。张飞大声喊道：“害民贼！你认得我吗？”督邮还没来得及说话，就被张飞揪住头发，拉出了馆驿，一直拖到县前的马桩上绑起来。张飞折下柳条，使劲儿地抽打督邮的双腿，一连打折了十几根柳条呢。

这时候，刘备正觉得纳闷，听到县前闹哄哄的，就问身边的人。身边的人说：“张将军绑了一个人在县前痛打。”刘备赶紧跑去看，发现被绑着打的竟然是督邮。刘备惊讶地问张飞为啥要打他，张飞说：“这种害老百姓的坏蛋，不打死留着干啥！”督邮赶紧向刘备求救：“玄德公，救我性命！”刘备是个特别仁慈的人，急忙叫张飞住手。这时候，关羽走过来，对刘备说：“兄长立了那么多大功，才只做了个县尉，现在还被督邮侮辱。我觉得这小地方就像长满荆棘的地方，不是凤凰待的地方。咱们不如杀了督邮，弃了官，回家乡去，再想更远大的办法。”刘备听了，就把印绶取下来，挂在督邮的脖子上，责备他说：“你害老百姓，本来应该杀了你，现在暂且饶你一命。我把印绶还给朝廷，从此就走啦。”督邮回去告诉了定州太守，太守报告了上级，派人来捉刘备他们。刘备、关羽、张飞三个人就去代州投奔刘恢。刘恢看刘备是汉室宗亲，就把他们留在家里。

再来说说十常侍的事儿。十常侍掌握了很大的权力，他们商量好了，只要有人不听他们的，就把人家杀掉。赵忠、张让派人向那些打败黄巾军的将士要金子和丝绸，要是不给，就向皇帝告状，把人家的官给免了。皇甫嵩、朱儁都不肯给，赵忠他们就奏请皇帝把他们的官都免了。皇帝还封赵忠他们做车骑将军，张让等十三个人都封了列侯。这样一来，朝廷的政事变得越来越糟糕，老百姓都怨声载道。于是，长沙的区星造反，渔阳的张举、张纯也反了。张举还自称天子，张纯自称大将军。

有一天，皇帝在后园和十常侍一起喝酒。谏议大夫刘陶跑到皇帝面前大哭起来。皇帝问他为啥哭，刘陶说：“天下马上就要有危险啦，陛下还在和这些宦官一起喝酒呢！”皇帝说：“国家太平着呢，有啥危险？”刘陶说：“到处都有盗贼起来，抢州郡。这些祸都是十常侍卖官害老百姓、欺骗皇帝造成的。朝廷里正直的人都走了，大祸就在眼前啦！”十常侍都摘下帽子，跪在皇帝面前说：“大臣们容不下我们，我们活不下去啦！求陛下让我们回家，我们把家产都拿出来帮助军队。”说完就大哭起来。皇帝生气地对刘陶说：“你家里也有伺候你的人，为啥就容不下我呢？”然后叫武士把刘陶拉出去斩了。刘陶大声喊：“我死了也不怕！可惜汉朝天下，四百多年啦，到现在一下子就要完啦！”武士刚要拉刘陶出去行刑，一个大臣大声说：“别动手，等我去劝劝皇帝。”大家一看，原来是司徒陈耽。陈耽进宫对皇帝说：“刘谏议犯了啥罪要被杀呀？”皇帝说：“他毁谤我的近臣，冒犯了我。”陈耽说：“天下的老百姓都想吃十常侍的肉，陛下却像敬父母一样敬他们。他们一点功劳都没有，却都封了列侯。而且封谞他们还和黄巾军勾结，想在朝廷里捣乱。陛下要是不自己反省，国家马上就要完蛋啦！”皇帝说：“封谞作乱的事儿还不清楚。十常侍里，难道就没有一两个忠臣吗？”陈耽急得用头撞台阶来劝皇帝。皇帝很生气，让人把他拉出去，和刘陶一起关进了监狱。这天夜里，十常侍就在监狱里把他们杀了。皇帝还假传诏书，让孙坚做长沙太守去讨伐区星。不到五十天，孙坚就传来捷报，江夏平定了，皇帝封孙坚为乌程侯。

接着，皇帝封刘虞为幽州牧，让他带兵去渔阳征讨张举、张纯。代州的刘恢写信推荐刘备去见刘虞。刘虞可高兴啦，让刘备做都尉，带着兵直接到贼人的老窝。刘备和贼人打了好几天仗，把贼人的锐气都打下去了。张纯特别凶暴，他的士兵都不想跟着他了，他帐下的头目把他杀了，带着人来投降。张举看到形势不好，就上吊死了。渔阳的叛乱都平定啦。刘虞向朝廷报告刘备的大功，朝廷就赦免了刘备鞭打督邮的罪，让他做下密丞，后来又升他做高堂尉。公孙瓒也向朝廷报告刘备以前的功劳，推荐他做别部司马，守平原县令。刘备在平原，有很多钱粮和兵马，又把地方治理得很好。刘虞因为平寇有功，被封做太尉。

中平六年夏天四月，灵帝病得很厉害，把大将军何进叫进宫里，商量后事。何进本来是个杀猪的，因为他妹妹进了宫做了贵人，生了皇子辩，后来就成了皇后。现在皇子辩做了皇帝，何进的权力可大啦。但是十常侍的权力也不小，他们互相争斗。何进想杀了十常侍，但是何太后不同意。袁绍就给何进出主意，说可以把各地的英雄都召到京城来，一起把宦官都杀了。主簿陈琳觉得这个办法不好，说这就像蒙着眼睛捉燕雀，是自己骗自己。国家大事不能这么办，何进应该自己果断地行动。但是何进不听，还说陈琳是懦夫。曹操却觉得这事儿很容易。

董太后也想掌权，她听了张让的话，垂帘听政，封皇子协为陈留王，董重为骠骑将军，让张让他们一起参与朝政。何太后不愿意董太后专权，就请董太后吃饭，劝她不要参与朝政。董太后很生气，还骂了何太后。何太后也生气了，两宫就吵起来了。何太后把何进叫进宫，说了这件事。何进和大臣们商量，让朝廷的大臣上奏说董太后本来是藩妃，不应该住在宫里，要把她迁回河间。还派人把董太后送走，又派兵围住董重的家，要他的印绶。董重没办法，就在后堂自杀了。张让他们用金子和珠宝贿赂何进的弟弟何苗和他的母亲舞阳君，让他们在何太后面前说好话，这样十常侍又得到了皇帝和太后的信任。

后来，何进暗地里派人在河间的驿庭把董太后毒死了，把她的棺材运回京城，葬在文陵。何进借口生病不出来。司隶校尉袁绍去见何进，说张让他们在外面说何进毒死了董太后，想做大事。现在不杀了这些宦官，以后一定会有大祸。何进说要再商量商量。可是何进身边的人把这话告诉了张让，张让又告诉了何苗，还送了很多贿赂给何苗。何苗就进宫对何太后说：“大将军辅佐新皇帝，不仁慈，只知道杀人。”

小朋友们，这一回的故事就讲到这里啦，是不是很精彩呀？`
	ctx = context.WithValue(ctx, "style", "适合7岁小朋友")
	res, err := ttsProvider.TextToSpeech(ctx, msg, "qianwen_test", "user123")
	if err != nil {
		t.Fatalf("Failed to generate speech: %v", err)
	}
	t.Logf("Generated speech: %s", res)
}
